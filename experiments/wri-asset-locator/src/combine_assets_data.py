@app.cell
def _(df_all, pd):
    ## Date time columns

    def coerce_year(series):
        """Extract 4-digit year from a mixed date column."""
        return pd.to_datetime(series, errors="coerce", utc=True).dt.year

    _last_updated_cols = ["date_last_updated", "updatedAt", "dataLastUpdated", "last_updated"]
    df_all["asset_last_updated_year"] = (pd.concat([coerce_year(df_all[c]) for c in _last_updated_cols], axis=1)
        .bfill(axis=1)
        .iloc[:, 0]
        .astype("Int64")  # nullable integer — handles NaN cleanly
    )

    _created_cols = ["date_created", "createdAt"]
    df_all["asset_created_year"] = (
        pd.concat([coerce_year(df_all[c]) for c in _created_cols], axis=1)
        .bfill(axis=1)
        .iloc[:, 0]
        .astype("Int64")
    )

    df_all[_last_updated_cols + ['asset_last_updated_year'] + _created_cols + ['asset_created_year']]
    return


